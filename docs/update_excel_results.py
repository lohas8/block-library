# 更新Excel
pass_count = 0
fail_count = 0
pending_count = 0

for row in range(2, ws.max_row + 1):
    case_id = ws.cell(row=row, column=1).value
    if case_id and case_id in test_results:
        result, reason = test_results[case_id]
        ws.cell(row=row, column=6, value=result)
        ws.cell(row=row, column=10, value=reason)  # 备注栏填入原因
        
        # 设置颜色
        if result == '通过':
            pass_fill_copy = PatternFill(start_color="C6EFCE", end_color="C6EFCE", fill_type="solid")
            for col in range(1, 11):
                ws.cell(row=row, column=col).fill = pass_fill_copy
            pass_count += 1
        elif result == '失败':
            fail_fill_copy = PatternFill(start_color="FFC7CE", end_color="FFC7CE", fill_type="solid")
            for col in range(1, 11):
                ws.cell(row=row, column=col).fill = fail_fill_copy
            fail_count += 1
        elif result == '待测试':
            pending_fill_copy = PatternFill(start_color="FFEB9C", end_color="FFEB9C", fill_type="solid")
            for col in range(1, 11):
                ws.cell(row=row, column=col).fill = pending_fill_copy
            pending_count += 1

# 更新统计sheet
ws_stats = wb['统计汇总']
# 找到总计行
total_row = ws_stats.max_row
ws_stats.cell(row=total_row, column=6, value=pass_count)
ws_stats.cell(row=total_row, column=7, value=f"{pass_count * 100 // (pass_count + fail_count + pending_count)}%" if (pass_count + fail_count + pending_count) > 0 else "0%")

# 保存
output_path = '/root/.openclaw/workspace/block-library/docs/测试用例表.xlsx'
wb.save(output_path)

print(f"✅ 测试结果已更新到: {output_path}")
print(f"📊 统计: 通过={pass_count}, 失败={fail_count}, 待测试={pending_count}")
print(f"📈 通过率: {pass_count * 100 // (pass_count + fail_count + pending_count) if (pass_count + fail_count + pending_count) > 0 else 0}%")
